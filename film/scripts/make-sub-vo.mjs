#!/usr/bin/env node
// Voice-over (+ optional music bed) for the Submission cut via ElevenLabs (Creator plan).
// Spoken numbers are built from src/data/sub.json, so they always match the screen.
// Writes public/audio/sub-vo-NN.mp3, src/data/subvo.json (with word timings for captions).
// Usage: ELEVENLABS_API_KEY=... node scripts/make-sub-vo.mjs [--music] [--print]
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const film = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const A = process.argv.slice(2);
const S = JSON.parse(fs.readFileSync(path.join(film, 'src/data/sub.json'), 'utf8'));

const ONES = 'zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen'.split(' ');
const TENS = ['', '', 'twenty', 'thirty', 'forty', 'fifty', 'sixty', 'seventy', 'eighty', 'ninety'];
const words = (n) => {
	n = Math.round(n);
	if (n < 20) return ONES[n];
	if (n < 100) return TENS[Math.floor(n / 10)] + (n % 10 ? '-' + ONES[n % 10] : '');
	if (n < 1000) return ONES[Math.floor(n / 100)] + ' hundred' + (n % 100 ? ' and ' + words(n % 100) : '');
	return String(n);
};
// spoken multipliers never exceed the floor-rounded figure on screen
const times = (x) => {
	const f = Math.floor(x * 10 + 1e-9) / 10;
	const i = Math.floor(f);
	const d = Math.round((f - i) * 10);
	if (d >= 7 && i >= 3) return `nearly ${words(i + 1)} times`;
	if (d === 0) return `${words(i)} times`;
	return `${words(i)} point ${words(d)} times`;
};
const cap = (t) => t[0].toUpperCase() + t.slice(1);
const B = S.bench;
const hb = S.hero.browser;
const hc = S.hero.cli;
const R = S.race;
const FRAC = ['', '', 'half', 'third', 'quarter', 'fifth', 'sixth', 'seventh', 'eighth', 'ninth', 'tenth'];
// race: the README's ratio of means over all generated-spec runs (scripts/counts.mjs), rounded like the screen
const say1 = (x) => {
	const [i, d] = x.toFixed(1).split('.').map(Number);
	return d ? `${words(i)} point ${words(d)} times` : `${words(i)} times`;
};
const raceLine = () => {
	const G = R.gen;
	const both = R.browser.success === R.browser.tasks && R.clify.success === R.clify.tasks;
	const res = both ? `Both finish all ${words(R.clify.tasks)}.` : `The CLI agent finishes ${words(R.clify.success)} of ${words(R.clify.tasks)}, the browser agent ${words(R.browser.success)}.`;
	return `${res} Over ${words(G.runs)} runs, the CLI agent is ${say1(G.means.time)} faster, and ${say1(G.means.cost)} cheaper.`;
};
const hundreds = (n) => words(n).replace(/^one hundred/, 'a hundred');
// 2,538 tokens -> "two and a half thousand" (floor to 0.1k, like the screen's "2.5k")
const thousands = (n) => {
	const f = Math.floor(n / 100) / 10;
	const i = Math.floor(f);
	const d = Math.round((f - i) * 10);
	return d === 0 ? `${words(i)} thousand` : d === 5 ? `${words(i)} and a half thousand` : `${words(i)} point ${words(d)} thousand`;
};
const T = S.mcp.tools;

// [scene, seconds into the scene, text]
const LINES = [
	['hook', 0.3, 'This is an agent doing real work in web dashboards. Click, screenshot, read, repeat.'],
	['race', 0.3, `Same agent, same jobs, same accounts. But this one gets each website as a CLI, ${R.gen.specs.split('/').map(Number).map(words).join(' of ')} generated by clify itself.`],
	['race', 9.0, raceLine()],
	['bench', 0.25, `On ${words(B.nTasks)} easy, public, read-only tasks, it's ${times(B.vsUi.faster)} faster too.`],
	['title', 0.15, 'This is clify. It turns websites into CLIs for agents.'],
	['add', 0.4, 'Give it a URL. An agent explores the site, records the requests behind what it clicks, and writes a command for each.'],
	['add', 7.3, 'Every command is tested live, and a fresh agent can do all of this by itself.'],
	['identity', 0.2, 'What blocks agents? Signups. No agent had a login.'],
	['identity', 3.7, 'So clify gives the agent its own email and phone number. It reads the terms, signs itself up, opens the verification email, and saves the session.'],
	['identity', 13.6, `${cap(words(S.accounts.signedIn))} real accounts so far, made by the agent itself${S.accounts.loggedIn === S.accounts.signedIn ? ', all logged in' : ''}.`],
	['ask', 0.3, 'When a site shows a CAPTCHA, clify never solves it. It emails its human, or another agent, and carries on from the reply.'],
	['mcp', 0.3, `The same tools run as one MCP server on Manufact: ${hundreds(S.mcp.hosted.sites)} sites behind ${words(T.core.tools)} core tools and ${words(T.deployed.tools - T.core.tools)} shortcuts. The whole tool list is ${thousands(T.deployed.tokens)} tokens.`],
	['agent', 0.2, 'It even lives on its own computer: an always-on email agent on InstaBox. Anyone can email it a job.'],
	['blaxel', 0.2, `And it scales: ${hundreds(S.blaxel.sites)} more sites, each explored and checked in its own Blaxel sandbox.`],
	['wall', 0.4, `Most websites become tools: ${hundreds(S.wall.distinctSites)} of ${hundreds(S.wall.attempted)} so far.`],
	['wall', 6.0, 'Every command on them was checked live.'],
	['end', 0.6, 'clify. The web, rebuilt for agents.'],
	// v11 cut only: replaces the bench line (appended so the other lines keep their files)
	['curl', 0.25, `Even against curl with the same logins, it's ${say1(S.curl.paired.time)} faster.`],
];
if (A.includes('--print')) {
	for (const l of LINES) console.log(`${l[0].padEnd(9)} +${l[1]}s  ${l[2]}`);
	process.exit(0);
}

const KEY = process.env.ELEVENLABS_API_KEY;
if (!KEY) throw new Error('ELEVENLABS_API_KEY missing');
const voice = A.includes('--voice') ? A[A.indexOf('--voice') + 1] : 'nPczCjzI2devNBz1zQrb'; // "Brian" premade
const out = path.join(film, 'public/audio');
fs.mkdirSync(out, {recursive: true});
const lines = [];
for (let i = 0; i < LINES.length; i++) {
	const [scene, at, text] = LINES[i];
	const base = `sub-vo-${String(i).padStart(2, '0')}`;
	const mp3 = path.join(out, `${base}.mp3`);
	const meta = path.join(out, `${base}.json`);
	let m = fs.existsSync(meta) ? JSON.parse(fs.readFileSync(meta, 'utf8')) : null;
	if (!m || m.text !== text || m.voice !== voice || !fs.existsSync(mp3)) {
		const r = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${voice}/with-timestamps?output_format=mp3_44100_128`, {
			method: 'POST',
			headers: {'xi-api-key': KEY, 'content-type': 'application/json'},
			body: JSON.stringify({text, model_id: 'eleven_multilingual_v2', voice_settings: {stability: 0.5, similarity_boost: 0.8, style: 0.2, use_speaker_boost: true, speed: 1.06}}),
		});
		if (!r.ok) throw new Error(`TTS ${r.status}: ${(await r.text()).slice(0, 300)}`);
		const j = await r.json();
		fs.writeFileSync(mp3, Buffer.from(j.audio_base64, 'base64'));
		const al = j.alignment;
		// characters → words with start/end seconds
		const ws = [];
		let cur = null;
		al.characters.forEach((ch, k) => {
			if (/\s/.test(ch)) {
				if (cur) ws.push(cur);
				cur = null;
				return;
			}
			if (!cur) cur = {w: '', s: al.character_start_times_seconds[k], e: 0};
			cur.w += ch;
			cur.e = al.character_end_times_seconds[k];
		});
		if (cur) ws.push(cur);
		m = {text, voice, dur: al.character_end_times_seconds.at(-1), words: ws};
		fs.writeFileSync(meta, JSON.stringify(m));
		console.log(`vo ${i} (${m.dur.toFixed(2)} s): ${text}`);
	}
	lines.push({scene, at, text, file: `audio/${base}.mp3`, dur: m.dur, words: m.words});
}

let music = null;
const mf = path.join(out, 'sub-music.mp3');
if (A.includes('--music') && !fs.existsSync(mf)) {
	const r = await fetch('https://api.elevenlabs.io/v1/music?output_format=mp3_44100_128', {
		method: 'POST',
		headers: {'xi-api-key': KEY, 'content-type': 'application/json'},
		body: JSON.stringify({
			prompt: 'Modern, confident tech product film score, instrumental, 104 BPM. 0-17 s: tense, sparse ticking pulse and low drone. At 17 s a clean lift: warm analog synth arpeggio and soft kick. Steady, optimistic build through the middle with crisp light percussion; a bigger lift around 82 s; calm, resolved, warm ending at 118 s with a soft final chord. No vocals. Understated, premium, not cheesy.',
			music_length_ms: 120000,
			force_instrumental: true,
		}),
	});
	if (!r.ok) throw new Error(`music ${r.status}: ${(await r.text()).slice(0, 300)}`);
	fs.writeFileSync(mf, Buffer.from(await r.arrayBuffer()));
	console.log('music written');
}
if (fs.existsSync(mf)) music = 'audio/sub-music.mp3';
fs.writeFileSync(path.join(film, 'src/data/subvo.json'), JSON.stringify({voice, music, lines}, null, 1));
console.log(`subvo.json: ${lines.length} lines, music ${music}`);
